static void Oled_ShowPicture(void)
{
    uint8_t page;
    uint8_t col;

    Oled_Write_Cmd(0xA4); /* Display RAM, cancel force-all-on test. */
    Oled_Write_Cmd(0xA6); /* Normal: 1 = lit, 0 = dark. */
    Oled_Write_Cmd(0x20);
    Oled_Write_Cmd(0x02); /* SSD1306 page addressing mode. */

    for (page = 0; page < 8; page++)
    {
        Oled_Write_Cmd((uint8_t)(0xB0 + page));
        Oled_Write_Cmd(0x00);
        Oled_Write_Cmd(0x10);
        for (col = 0; col < 128; col++)
        {
            Oled_Write_Data(oled_picture[(uint16_t)page * 128 + col]);
        }
    }
}

